def wolf_tactics():
    rows = []
    for i, (tag, good, bad, plan, speech, alternate, alt_speech) in enumerate(TACTICS, 1):
        for variant in ("正确使用", "错误使用", "被识破", "对方反制", "调整策略"):
            row = new_sample(f"tactic-{i:02d}-{variant}", "werewolf", 7, round_no=2, training_stage="tactics")
            row["scenario_id"] = f"tactic-family-{i:02d}"
            for teammate in (2, 5, 11):
                add_fact(row, "wolf_team", teammate, "werewolf", round_no=1)
            if variant == "正确使用":
                context, strategy, public = good, plan, speech
                analysis = "2、5、11是私有已知队友。" + good + "该做法有条件收益，不保证他人接受。"
            else:
                prefix = {
                    "错误使用": "",
                    "被识破": "6号引用你上轮原话，指出你的公开理由与行为不一致。",
                    "对方反制": "3号要求先核对逐字记录和票型，不接受仅凭身份称呼归票。",
                    "调整策略": "最初情况：" + good + "随后信息更新：",
                }[variant]
                context, strategy, public = prefix + bad, alternate, alt_speech
                analysis = bad + "继续照搬原做法会增加身份或轮次成本，应按新证据调整。"
            add_event(row, context, actor=6)
            row.update(task="现在轮到7号，依据已知信息选择行动并发言。",
                       analysis=analysis, strategy=strategy, public_response=public,
                       tactical_tags=[tag, variant], wolf_pit="私有已知2、5、11与我同阵营；公开不泄露队友表。")
            if tag in {"自刀", "刀法规划"}:
                row["stage"], row["task"], row["public_response"] = "night", "选择今晚狼刀目标或空刀。", ""
                row["action"] = action("knife", (7 if tag == "自刀" else 3) if variant == "正确使用" else 8)
                if tag == "自刀" and variant == "正确使用":
                    row["round"] = 1
                    row["public_info"]["events"] = []
                    row["evidence_ids"] = [f["id"] for f in row["private_info"]["facts"]]
                    row["task"] = "首夜选择刀口。我愿承担可能无法获救的风险以争取白天发言空间。"
            if tag == "假警徽流" and variant != "正确使用":
                row["public_info"]["alive"].remove(4)
            rows.append(row)
    return rows


